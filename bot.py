"""
Discord Bot for Stonks - Cryptocurrency and Stock Price Comparison

This bot responds to `!stonks` messages and the `/stonks` slash command
with price comparison charts generated by the stonks module.
"""

import asyncio
import io
import logging
import math
import os
import sys
import time

import discord
from discord import app_commands
from dotenv import load_dotenv

from stonks import (
    COMMAND_PREFIX,
    DEFAULT_DAYS,
    MAX_DAYS,
    MIN_DAYS,
    StonksError,
    describe_failures,
    get_chart_png,
    log_level_from_env,
    parse_request,
)

logger = logging.getLogger(__name__)

# Per-user cooldown between charts, and how many charts may be generated at once
COOLDOWN_SECONDS = 10
MAX_CONCURRENT_CHARTS = 2

_last_request: dict[int, float] = {}
_chart_slots = asyncio.Semaphore(MAX_CONCURRENT_CHARTS)


class StonksClient(discord.Client):
    """Discord client that also registers the /stonks slash command."""

    def __init__(self):
        intents = discord.Intents.default()
        intents.message_content = True  # required to read "!stonks" messages
        # Replies can contain user input, so never let them ping @everyone, roles or users
        super().__init__(intents=intents, allowed_mentions=discord.AllowedMentions.none())
        self.tree = app_commands.CommandTree(self)

    async def setup_hook(self) -> None:
        """Register the slash commands with Discord."""
        try:
            synced = await self.tree.sync()
            logger.info("Synced %d slash command(s)", len(synced))
        except discord.HTTPException as e:
            logger.warning("Could not sync slash commands: %s", e)


client = StonksClient()


def cooldown_remaining(user_id: int) -> float:
    """Seconds the user still has to wait; 0 starts a new cooldown."""
    now = time.monotonic()
    last = _last_request.get(user_id)
    if last is not None and now - last < COOLDOWN_SECONDS:
        return COOLDOWN_SECONDS - (now - last)
    _last_request[user_id] = now
    if len(_last_request) > 1000:
        # Forget users whose cooldown has expired
        for uid, started in list(_last_request.items()):
            if now - started >= COOLDOWN_SECONDS:
                del _last_request[uid]
    return 0.0


async def make_chart(days: int, tickers: list[str]) -> tuple[discord.File, str]:
    """Generate a chart; returns the file to upload and the message to send with it."""
    async with _chart_slots:
        png, failures = await get_chart_png(days, tickers)
    text = "Here's your stonks chart!"
    if failures:
        text += f"\nSkipped {describe_failures(failures)}"
    return discord.File(io.BytesIO(png), filename="stonks_chart.png"), text


@client.event
async def on_message(message: discord.Message) -> None:
    """Handle incoming Discord messages."""
    # Ignore other bots and the bot itself
    if message.author.bot:
        return

    # Parse command (attachment-only and system messages have no text)
    command_parts = message.content.split()
    if not command_parts or command_parts[0] != COMMAND_PREFIX:
        return

    logger.info("Received stonks command from %s: %s", message.author, message.content)

    try:
        days, tickers = parse_request(command_parts[1:])
    except StonksError as e:
        await message.channel.send(f"Error: {e}")
        return

    wait = cooldown_remaining(message.author.id)
    if wait:
        await message.channel.send(f"Slow down! Try again in {math.ceil(wait)}s.")
        return

    # Send initial response
    await message.channel.send("Generating your stonks chart...")

    try:
        file, text = await make_chart(days, tickers)
    except StonksError as e:
        logger.warning("StonksError for user %s: %s", message.author, e)
        await message.channel.send(f"Error generating chart: {e}")
        return
    except Exception:
        logger.exception("Unexpected error for user %s", message.author)
        await message.channel.send("Unexpected error while generating the chart.")
        return

    # Send the chart
    try:
        await message.channel.send(text, file=file)
    except discord.HTTPException as e:
        logger.error("Error sending chart: %s", e)
        try:
            await message.channel.send("Couldn't upload the chart. Does the bot have the Attach Files permission?")
        except discord.HTTPException:
            pass


@client.tree.command(name="stonks", description="Normalized price comparison chart for crypto and stocks")
@app_commands.describe(
    days=f"Number of days to show ({MIN_DAYS}-{MAX_DAYS}; crypto data only goes back 365 days)",
    tickers="Space-separated tickers, e.g. BTC ETH X:AAPL (default: BTC ETH XMR AVAX)",
)
async def stonks_command(
    interaction: discord.Interaction,
    days: app_commands.Range[int, MIN_DAYS, MAX_DAYS] = DEFAULT_DAYS,
    tickers: str | None = None,
) -> None:
    """Handle the /stonks slash command."""
    try:
        days, ticker_list = parse_request([str(days), *(tickers or "").split()])
    except StonksError as e:
        await interaction.response.send_message(f"Error: {e}", ephemeral=True)
        return

    wait = cooldown_remaining(interaction.user.id)
    if wait:
        await interaction.response.send_message(f"Slow down! Try again in {math.ceil(wait)}s.", ephemeral=True)
        return

    # Shows "thinking..." while the chart is generated
    await interaction.response.defer(thinking=True)

    try:
        file, text = await make_chart(days, ticker_list)
    except StonksError as e:
        logger.warning("StonksError for user %s: %s", interaction.user, e)
        await interaction.followup.send(f"Error generating chart: {e}")
        return
    except Exception:
        logger.exception("Unexpected error for user %s", interaction.user)
        await interaction.followup.send("Unexpected error while generating the chart.")
        return

    await interaction.followup.send(text, file=file)


@client.event
async def on_ready():
    """Called when the bot is ready."""
    logger.info("%s is online and ready!", client.user)
    logger.info("Bot ID: %s", client.user.id)
    logger.info("Connected to %d guild(s)", len(client.guilds))

    # Set bot status
    await client.change_presence(
        activity=discord.Activity(
            type=discord.ActivityType.watching,
            name="!stonks for charts"
        )
    )


@client.event
async def on_error(event, *args, **kwargs):
    """Handle Discord client errors."""
    # discord.py calls this from inside its except block, so exc_info has the traceback
    logger.error("Discord client error in event %s", event, exc_info=True)  # noqa: LOG014


def main():
    """Main function to run the Discord bot."""
    load_dotenv()
    logging.basicConfig(level=log_level_from_env(), format="%(asctime)s %(levelname)s %(name)s: %(message)s")

    # Get Discord token from environment
    token = os.getenv("DISCORD_TOKEN")
    if not token:
        logger.error("DISCORD_TOKEN environment variable not set!")
        sys.exit(1)

    try:
        logger.info("Starting Discord bot...")
        # Logging is configured above; discord.py's default handler would print every line twice
        client.run(token, log_handler=None)
    except discord.LoginFailure:
        logger.error("Invalid Discord token!")
        sys.exit(1)
    except discord.PrivilegedIntentsRequired:
        logger.error(
            "Enable the Message Content Intent in the Discord Developer Portal "
            "(your application > Bot > Privileged Gateway Intents)."
        )
        sys.exit(1)


if __name__ == "__main__":
    main()
